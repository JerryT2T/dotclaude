function oneLine(s, n = 160) {
  const v = String(s || '').replace(/\s+/g, ' ').trim();
  return v.length > n ? `${v.slice(0, n - 1)}…` : v;
}

function appendLog(ctx, status, detail = '') {
  try {
    const file = inClaude(ctx, LOG_FILE);
    const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').split('\n').filter(Boolean) : [];
    old.push(`${ctx.now().toISOString()} ${status}${detail ? ` ${detail}` : ''}`);
    fs.writeFileSync(file, `${old.slice(-LOG_KEEP).join('\n')}\n`);
  } catch { /* the log is a convenience */ }
}

