#!/usr/bin/env node
'use strict';
/**
 * @script home-backup
 * @version 0.2.0
 * @plugin devops
 * @description Opt-in backup of the allowlisted part of ~/.claude (settings,
 *   agents, own skills/commands, memory, scripts, routines) to one target:
 *   a PRIVATE GitHub repo, a folder (local disk, NAS share, a Google Drive
 *   for Desktop folder), an rclone remote, or the user's own command.
 *   The daily run is pure node on the OS scheduler — zero model tokens;
 *   post.backup.routine starts the same run right after a recurring routine
 *   was created or changed.
 *
 *   ~/.claude/.git is the staging engine for every target. Retention keeps
 *   the newest state plus older versions — at most one per day, from
 *   `homeBackup.keepDays` (default 4) different days: a second run on the
 *   same day amends that day's commit, and older days are cut from the
 *   history (github: force-with-lease push) or deleted as dated folders.
 *
 *   Safety model, strictest first: (1) the generated .gitignore is
 *   deny-by-default; (2) a code-level denylist unstages secret-looking paths
 *   even if the .gitignore was edited; (3) symlinks/junctions are never
 *   staged; (4) every staged file is scanned for secrets and private data
 *   (lib/backup-scan.js) — any hit unstages everything, writes a report with
 *   file+line+rule (never values), notifies, and nothing is committed or
 *   pushed. Commits use a fixed local identity, never the user's e-mail.
 *
 *   Runbook: deep-knowledge/home-backup.md.
 *
 * Usage:
 *   home-backup.js setup --repo <owner>/<name>   one-time setup, idempotent (target github)
 *   home-backup.js setup --target folder --path <dir>
 *   home-backup.js setup --target drive            Google Drive for Desktop folder, detected
 *   home-backup.js setup --target rclone --remote <name>:<folder>
 *   home-backup.js setup --target command --command "<shell command>"
 *   home-backup.js run                           the scheduled job
 *   home-backup.js scan                          dry run of both scans
 *   home-backup.js status                        switches, job, last result
 *   home-backup.js disable                       unregister job, switch off
 *   home-backup.js render-gitignore              print the .gitignore
 *
 * Exit codes:
 *   0  ok (also: disabled, or nothing changed)
 *   1  blocked by a scan hit, or a git/gh/scheduler step failed
 *   2  usage error
 */

